-- Supabase setup for the Digital Electronics Lab website.
-- Run this entire file once in Supabase: SQL Editor > New query > Run.
-- It creates application data tables and one private bucket for original files.

begin;

create table if not exists public.users (
    id bigint generated by default as identity primary key,
    username text not null unique,
    full_name text not null,
    password_hash text not null,
    role text not null check (role in ('admin', 'staff', 'lecturer', 'student')),
    active boolean not null default true
);

create table if not exists public.items (
    id bigint generated by default as identity primary key,
    code text not null unique,
    name text not null,
    category text not null default 'Khác',
    location text not null default '',
    quantity integer not null default 1 check (quantity >= 0),
    minimum_stock integer not null default 0 check (minimum_stock >= 0),
    unit_price bigint check (unit_price is null or unit_price >= 0),
    notes text not null default '',
    image_path text not null default '',
    created_at timestamptz not null default current_timestamp
);

create table if not exists public.loans (
    id bigint generated by default as identity primary key,
    item_id bigint not null references public.items(id),
    borrower_id bigint not null references public.users(id),
    borrower_name text not null default '',
    quantity integer not null check (quantity > 0),
    purpose text not null,
    borrowed_at text not null,
    due_at text not null,
    issued_by bigint not null references public.users(id),
    giver_signature text not null,
    receiver_signature text not null,
    returned_at text,
    received_by bigint references public.users(id),
    return_signature text not null default ''
);

create index if not exists items_category_name_idx on public.items (category, name);
create index if not exists loans_open_due_at_idx on public.loans (due_at) where returned_at is null;
create index if not exists loans_item_id_idx on public.loans (item_id);

-- These tables are accessed only by Flask through the PostgreSQL connection.
-- No browser receives a Supabase Data API key, so do not create public policies.
alter table public.users enable row level security;
alter table public.items enable row level security;
alter table public.loans enable row level security;

-- The bucket stays private. Only the Flask server uses the service-role key;
-- it retrieves original images and returns a watermarked WebP response instead.
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values (
    'lab-files',
    'lab-files',
    false,
    4194304,
    array['image/jpeg', 'image/png', 'image/webp', 'image/gif']::text[]
)
on conflict (id) do update set
    public = excluded.public,
    file_size_limit = excluded.file_size_limit,
    allowed_mime_types = excluded.allowed_mime_types;

commit;
